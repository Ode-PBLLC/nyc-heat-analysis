/* NYC's A/C Gap — page script.
   Data comes from site/bundle.js (window.NYC_HEAT_DATA), generated by build_site.py from each
   visualization's data/ directory. The page formats and draws those values; it computes nothing else. */
'use strict';

const $ = id => document.getElementById(id);
const NS = 'http://www.w3.org/2000/svg';
const DATA = window.NYC_HEAT_DATA;
if (!DATA) throw new Error('site/bundle.js did not load. Run `python3 build_site.py` to regenerate it.');
const load = name => { if (!Object.hasOwn(DATA, name)) throw new Error('Missing bundled data: ' + name); return DATA[name]; };
const P01 = '01_heat_vulnerability_map/data/', P02 = '02_no_working_ac/data/', P03 = '03_days_at_or_above_90f/data/', P04 = '04_heat_vulnerability_overlap/data/';

function node(tag, attrs = {}, text) { const e = document.createElementNS(NS, tag); for (const [k, v] of Object.entries(attrs)) e.setAttribute(k, v); if (text !== undefined) e.textContent = text; return e; }
function el(tag, text, cls) { const e = document.createElement(tag); if (text !== undefined) e.textContent = text; if (cls) e.className = cls; return e; }
// Equirectangular projection centred on New York City; longitude scaled by cos(41°) ≈ 0.76 relative to latitude.
const xy = ([lon, lat]) => [(lon + 74.3) * 760, -(lat - 41) * 1000];
const rings = g => g.type === 'Polygon' ? g.coordinates : g.coordinates.flat();
const path = g => rings(g).map(r => r.map((p, i) => (i ? 'L' : 'M') + xy(p).join(',')).join('') + 'Z').join('');
function bounds(fs, pad = 15) {
  const pts = fs.flatMap(f => rings(f.geometry).flat().map(xy)), xs = pts.map(p => p[0]), ys = pts.map(p => p[1]);
  const x = Math.min(...xs), y = Math.min(...ys), w = Math.max(...xs) - x, h = Math.max(...ys) - y;
  return [x - pad, y - pad, w + 2 * pad, h + 2 * pad];
}
// Label anchor: area centroid of the feature's largest ring (bbox centres land in water for Queens/Bronx).
function labelPoint(f) {
  let best = null, bestArea = -1;
  for (const ring of rings(f.geometry)) {
    const pts = ring.map(xy); let a = 0, cx = 0, cy = 0;
    for (let i = 0, n = pts.length; i < n; i++) { const [x0, y0] = pts[i], [x1, y1] = pts[(i + 1) % n], c = x0 * y1 - x1 * y0; a += c; cx += (x0 + x1) * c; cy += (y0 + y1) * c; }
    if (Math.abs(a) > bestArea) { bestArea = Math.abs(a); best = a ? [cx / (3 * a), cy / (3 * a)] : pts[0]; }
  }
  return best;
}
const fmt = v => v == null ? 'No data' : Number(v).toLocaleString(undefined, { maximumFractionDigits: 2 });
function table(target, headers, rows) {
  const t = document.createElement('table'), head = t.createTHead().insertRow();
  headers.forEach(h => { const th = el('th', h); th.scope = 'col'; head.append(th); });
  const body = t.createTBody();
  rows.forEach(row => { const tr = body.insertRow(); row.forEach(v => { tr.insertCell().textContent = v ?? 'No data'; }); });
  target.replaceChildren(t);
}
function clampCard(card, event, shape, { flip = false } = {}) {
  const box = shape.getBoundingClientRect(), w = card.offsetWidth, h = card.offsetHeight;
  const px = event && Number.isFinite(event.clientX) ? event.clientX : box.x + box.width / 2;
  const py = event && Number.isFinite(event.clientY) ? event.clientY : box.y + box.height / 2;
  let left = px + 16, top = py + 16;
  if (flip) { if (left + w > innerWidth - 12) left = px - w - 16; if (top + h > innerHeight - 12) top = py - h - 16; }
  card.style.left = Math.max(12, Math.min(left, innerWidth - w - 12)) + 'px';
  card.style.top = Math.max(12, Math.min(top, innerHeight - h - 12)) + 'px';
}

/* ---------- I. Scrolly map ---------- */
function scrolly() {
  const config = load(P01 + 'layers.json');
  const boroughs = load(P01 + config.boroughs.file).features;
  const ntas = load(P01 + config.neighborhoods_file).features;
  const council = load(P01 + config.council.file).features;
  const layers = Object.fromEntries(config.layers.map(l => [l.id, l]));
  const councilSpec = config.council;
  const NEUTRAL = '#d9d5d0';
  const svg = $('stage-map'), canvas = svg.parentElement;
  svg.setAttribute('viewBox', bounds(boroughs, 20).join(' '));

  const valueLabels = { hvi: 'Heat vulnerability', no_ac: 'Households without AC', black: 'Black, non-Hispanic residents', hispanic: 'Hispanic residents (any race)' };
  const nameOf = f => f.properties.ntaname || f.properties.boroname || ('Council District ' + f.properties.coundist);

  function group(id, features, fill, extra) {
    const g = node('g', { class: 'layer', id, 'data-active': 'false' });
    features.forEach(f => {
      const p = node('path', { d: path(f.geometry), fill: fill(f), 'fill-rule': 'evenodd', tabindex: -1, 'aria-label': nameOf(f) });
      if (extra) extra(p, f);
      g.append(p);
    });
    svg.append(g);
    return g;
  }
  const gBoroughs = group('layer-boroughs', boroughs, () => NEUTRAL);
  boroughs.forEach(f => { const [x, y] = labelPoint(f); gBoroughs.append(node('text', { x, y, 'text-anchor': 'middle' }, f.properties.boroname)); });
  const gNta = group('layer-neighborhoods', ntas, () => NEUTRAL);
  // Council outline styling comes from layers.json (stroke, width, dash) via CSS custom properties, so the stylesheet's shared path rule cannot override it.
  svg.style.setProperty('--council-stroke', councilSpec.stroke);
  svg.style.setProperty('--council-width', councilSpec.stroke_width);
  svg.style.setProperty('--council-dash', councilSpec.stroke_dasharray);
  const gCouncil = group('layer-council', council, () => NEUTRAL, p => p.classList.add('council'));
  council.forEach(f => { const [x, y] = labelPoint(f); gCouncil.append(node('text', { class: 'district', x, y: y + 3, 'text-anchor': 'middle' }, f.properties.coundist)); });

  const steps = [...document.querySelectorAll('#steps .step')].map(s => s.dataset.step);
  const progress = $('progress');
  steps.forEach(() => progress.append(el('span')));

  // Hover card
  const card = el('div', undefined, 'map-hover'); card.id = 'stage-hover'; card.role = 'tooltip'; card.hidden = true; canvas.append(card);
  let activeId = null, inspected = null, hideTimer = null;
  const featureOf = { 'layer-boroughs': boroughs, 'layer-neighborhoods': ntas, 'layer-council': council };
  function hide() { clearTimeout(hideTimer); card.hidden = true; card.classList.remove('is-touch'); if (inspected) inspected.classList.remove('is-inspected'); inspected = null; }
  function show(feature, shape, event) {
    clearTimeout(hideTimer);
    if (inspected && inspected !== shape) inspected.classList.remove('is-inspected');
    inspected = shape; shape.classList.add('is-inspected');
    const p = feature.properties, layer = layers[activeId];
    card.replaceChildren(el('h3', nameOf(feature)));
    if (p.nta2020) card.append(el('p', p.boroname, 'hover-area'));
    if (layer && layer.value_field) {
      const dl = document.createElement('dl'), row = document.createElement('div'), v = p[layer.value_field];
      row.append(el('dt', valueLabels[layer.id]), el('dd', v == null ? 'No data available' : fmt(v) + (layer.unit === '%' ? '%' : ' out of 5')));
      dl.append(row); card.append(dl);
    }
    card.hidden = false;
    const touch = event && event.pointerType === 'touch';
    card.classList.toggle('is-touch', !!touch);
    if (!touch) clampCard(card, event, shape);
    $('status').textContent = card.textContent;
  }
  for (const g of [gBoroughs, gNta, gCouncil]) {
    const features = featureOf[g.id];
    [...g.querySelectorAll('path')].forEach((shape, i) => {
      shape.onpointerenter = e => { if (e.pointerType !== 'touch') show(features[i], shape, e); };
      shape.onpointermove = e => { if (!card.hidden && inspected === shape && e.pointerType !== 'touch') clampCard(card, e, shape); };
      shape.onpointerleave = () => { hideTimer = setTimeout(hide, 80); };
      shape.onclick = e => show(features[i], shape, e);
    });
  }
  document.addEventListener('keydown', e => { if (e.key === 'Escape') hide(); });
  document.addEventListener('pointerdown', e => { if (!svg.contains(e.target)) hide(); });
  window.addEventListener('resize', hide);

  function legendFor(layer) {
    const box = $('chip-legend'); box.replaceChildren();
    if (!layer || !layer.colors) return;
    const labels = layer.id === 'hvi'
      ? ['1 · lowest', '2', '3', '4', '5 · highest']
      : layer.breakpoints.map((v, i) => i === 0 ? `0–${v}%` : `>${layer.breakpoints[i - 1]}–${v}%`).concat(`>${layer.breakpoints.at(-1)}%`);
    layer.colors.concat(layer.no_data_color).forEach((color, i) => {
      const item = el('span'), swatch = el('span', undefined, 'swatch'); swatch.style.background = color;
      item.append(swatch, document.createTextNode(labels[i] ?? 'No data'));
      box.append(item);
    });
  }
  function setStep(id) {
    if (id === activeId) return;
    activeId = id; hide();
    const layer = layers[id];
    gBoroughs.dataset.active = String(id === 'boroughs');
    gCouncil.dataset.active = String(id === 'council');
    gNta.dataset.active = String(!!(layer && layer.value_field));
    if (layer && layer.color_field) [...gNta.children].forEach((p, i) => p.setAttribute('fill', ntas[i].properties[layer.color_field]));
    const spec = id === 'council' ? councilSpec : id === 'boroughs' ? config.boroughs : layer;
    $('chip-title').textContent = spec.title;
    $('chip-note').textContent = spec.note;
    legendFor(layer);
    [...progress.children].forEach((dot, i) => dot.classList.toggle('is-on', steps[i] === id));
    $('scroll-hint').classList.toggle('is-hidden', id !== steps[0]);
    $('status').textContent = spec.title + '. ' + spec.note;
  }
  const observer = new IntersectionObserver(entries => {
    entries.filter(e => e.isIntersecting).forEach(e => setStep(e.target.dataset.step));
  }, { rootMargin: '-50% 0px -50% 0px', threshold: 0 });
  document.querySelectorAll('#steps .step').forEach(s => observer.observe(s));
  setStep(steps[0]);
}

/* ---------- II. 0 in 25 ---------- */
function zeroIn25() {
  const d = load(P02 + 'ac_status.json'), box = $('ac');
  const headline = el('div', `${d.working_and_used} in ${d.denominator}`, 'stat');
  headline.setAttribute('role', 'img');
  headline.setAttribute('aria-label', `${d.working_and_used} in ${d.denominator}: none had a working air conditioner in use`);
  const sub = el('p', `${d.period} · AC status known · ${d.denominator} people`, 'stat-sub');
  const bars = el('div', undefined, 'bars'); bars.setAttribute('role', 'list');
  d.categories.forEach(c => {
    const label = el('span', c.label, 'label'), track = el('div', undefined, 'track'), fill = el('div', undefined, 'fill'), value = el('span', `${c.count} (${c.percent}%)`, 'value');
    fill.style.width = c.percent + '%'; if (c.count === 0) fill.classList.add('is-zero');
    track.append(fill); track.setAttribute('role', 'listitem'); track.setAttribute('aria-label', `${c.label}: ${c.count} of ${d.denominator}, ${c.percent}%`);
    bars.append(label, track, value);
  });
  box.append(headline, sub, bars, el('p', d.note, 'note'));
}

/* ---------- III. Days at or above 90°F ---------- */
function chart() {
  const d = load(P03 + 'days_at_or_above_90f.json'), s = d.series, svg = $('chart');
  const x = yr => 80 + (yr - 1995) / 90 * 750, y = v => 400 - v / 120 * 340;
  for (let v = 0; v <= 120; v += 20) { svg.append(node('line', { x1: 80, x2: 830, y1: y(v), y2: y(v), stroke: '#d5d2ce' })); svg.append(node('text', { x: 65, y: y(v) + 5, 'text-anchor': 'end' }, v)); }
  svg.append(node('text', { x: 80, y: 30 }, 'Days per year'));
  const line = q => s.map((r, i) => (i ? 'L' : 'M') + x(r.year) + ',' + y(r[q])).join('');
  for (const [a, b, opacity] of [['p10', 'p90', .15], ['p25', 'p75', .38]]) svg.append(node('path', { d: line(a) + [...s].reverse().map(r => 'L' + x(r.year) + ',' + y(r[b])).join('') + 'Z', fill: '#c60101', 'fill-opacity': opacity }));
  for (const q of ['p25', 'p75']) svg.append(node('path', { d: line(q), fill: 'none', stroke: '#c60101', 'stroke-width': 2.5 }));
  s.forEach(r => {
    svg.append(node('text', { x: x(r.year), y: 433, 'text-anchor': 'middle' }, r.observed ? '1981–2010' : r.period));
    for (const q of ['p25', 'p75']) { const dot = node('circle', { cx: x(r.year), cy: y(r[q]), r: 4, fill: '#c60101', tabindex: 0 }); dot.append(node('title', {}, r.period + ': ' + r[q] + ' days (' + q + ')')); svg.append(dot); }
  });
  const baseline = s.find(r => r.observed);
  const label = node('text', { x: 91, y: y(baseline.p25) + 24, id: 'baseline-label' });
  label.append(node('tspan', { x: 91 }, `${baseline.p25} days at or above 90°F`));
  label.append(node('tspan', { x: 91, dy: 20 }, 'per year, 1981–2010 average'));
  svg.append(label);
}

/* ---------- IV. Bivariate map ---------- */
function bivariate() {
  const d = load(P04 + 'modzcta_bivariate.geojson'), l = load(P04 + 'legend.json'), city = load(P04 + 'citywide_context.json');
  const svg = $('biv-map'), status = $('biv-status'), legend = $('biv-legend');
  svg.setAttribute('viewBox', bounds(d.features).join(' '));
  let active = l.comparisons[0];
  const tip = f => { const p = f.properties; return `${p.label} · ${p.nta_names} · HVI ${fmt(p.hvi_popwtd)} · ${active.title}: ${fmt(p[active.field])} · Applications: ${fmt(p.applications_2025)}`; };
  const group = node('g'); svg.append(group);
  d.features.forEach(f => group.append(node('path', { d: path(f.geometry), fill: f.properties[active.color_column], 'fill-rule': 'evenodd', tabindex: 0, 'aria-label': tip(f) })));
  const shapes = [...group.children];
  const context = el('p', undefined, 'citywide-context'); context.id = 'citywide-context'; status.insertAdjacentElement('afterend', context);
  const card = el('div', undefined, 'map-hover'); card.id = 'biv-hover'; card.role = 'tooltip'; card.hidden = true; card.style.pointerEvents = 'auto'; document.body.append(card);
  let inspected = null, pinned = false, hideTimer = null;
  const help = 'Hover, focus or tap an area to see its values.';
  function hideCard() { clearTimeout(hideTimer); card.hidden = true; pinned = false; inspected = null; shapes.forEach(p => { p.classList.remove('is-inspected'); p.removeAttribute('aria-describedby'); }); status.textContent = help; }
  function showCard(index, event) {
    clearTimeout(hideTimer); inspected = index;
    const p = d.features[index].properties, shape = shapes[index];
    const values = document.createElement('dl');
    const rows = [['Heat vulnerability', p.hvi_popwtd == null ? 'No data' : fmt(p.hvi_popwtd) + ' / 5']];
    if (active.id === 'apps') rows.push(['Applications per 1,000 residents', fmt(p.apps_1k)], ['Applications · 2025', fmt(p.applications_2025)], ['Population denominator', fmt(p.pop_est)]);
    else rows.push([active.id === 'black' ? 'Black, non-Hispanic residents' : 'Hispanic residents (any race)', p[active.field] == null ? 'No data' : fmt(p[active.field]) + '%']);
    rows.forEach(([label, value]) => { const row = document.createElement('div'); row.append(el('dt', label), el('dd', value)); values.append(row); });
    card.replaceChildren(el('h3', p.nta_names || 'Neighborhood name unavailable'), el('p', 'Modified ZIP area ' + p.label, 'hover-area'), values, el('p', 'HVI: population-weighted neighborhood score.' + (active.id === 'apps' ? ' Applications: DSS, 2025.' : ' Demographics: 2020 Census.'), 'hover-note'));
    card.hidden = false;
    shapes.forEach((s, i) => { s.classList.toggle('is-inspected', i === index); s.removeAttribute('aria-describedby'); }); shape.setAttribute('aria-describedby', card.id);
    status.textContent = help; clampCard(card, event, shape, { flip: true });
  }
  function scheduleHide() { clearTimeout(hideTimer); if (!pinned && !group.contains(document.activeElement)) hideTimer = setTimeout(hideCard, 120); }
  shapes.forEach((shape, index) => {
    shape.onfocus = () => { pinned = false; showCard(index); };
    shape.onpointerenter = e => { if (e.pointerType === 'touch') return; pinned = false; showCard(index, e); };
    shape.onpointermove = e => { if (!card.hidden && inspected === index && !pinned && e.pointerType !== 'touch') clampCard(card, e, shape, { flip: true }); };
    shape.onpointerleave = scheduleHide; shape.onblur = () => { if (!pinned) hideCard(); };
    shape.onclick = e => { pinned = true; showCard(index, e); };
    shape.onkeydown = e => { if (e.key === 'Enter' || e.key === ' ') { e.preventDefault(); pinned = true; showCard(index); } };
  });
  card.onpointerenter = () => clearTimeout(hideTimer); card.onpointerleave = scheduleHide;
  document.addEventListener('keydown', e => { if (e.key === 'Escape') hideCard(); });
  document.addEventListener('pointerdown', e => { if (!svg.contains(e.target) && !card.contains(e.target)) hideCard(); });
  window.addEventListener('scroll', hideCard, { passive: true }); window.addEventListener('resize', hideCard);

  const buttons = [];
  function select(c) {
    hideCard(); active = c;
    shapes.forEach((p, i) => { p.setAttribute('fill', d.features[i].properties[c.color_column]); p.setAttribute('aria-label', tip(d.features[i])); });
    buttons.forEach(([b, k]) => b.setAttribute('aria-pressed', String(k === c.id)));
    const xCuts = c.edges.slice(1, 3); if (c.inverted) xCuts.reverse();
    const cutLabel = v => c.id === 'apps' ? fmt(v) : Number(v).toLocaleString(undefined, { maximumFractionDigits: 1 }) + '%';
    const yTicks = [...l.hvi_edges.slice(1, 3)].reverse().map((v, i) => `<span style="top:${(i + 1) * 100 / 3}%">${fmt(v)}</span>`).join('');
    const xTicks = xCuts.map((v, i) => `<span style="left:${(i + 1) * 100 / 3}%">${cutLabel(v)}</span>`).join('');
    legend.innerHTML = '<div class="bivariate-legend"><div class="legend-y"><span>Higher heat<br>vulnerability</span><span class="direction" aria-label="increases upward">↑</span></div><div class="legend-y-ticks" aria-label="Heat vulnerability breakpoints">' + yTicks + '</div><div class="legend-grid">' + [...l.palette].reverse().flat().map(color => `<span style="background:${color}"></span>`).join('') + '</div><div class="legend-x-ticks" aria-label="' + c.title + ' breakpoints">' + xTicks + '</div><div class="legend-x">' + c.axis_right + '</div></div><div class="legend-meta">Breakpoints are rounded.<br><span class="swatch" style="background:' + l.no_data_color + '"></span>No data (' + c.no_data + ' zones)</div>';
    const hviContext = ' The population-weighted average heat-vulnerability score across NYC’s ' + city.hvi_scored_neighborhoods + ' scored neighborhoods is ' + fmt(city.hvi_population_weighted_mean) + ' out of 5, calculated using 2020 Census populations.';
    context.textContent = (c.id === 'apps'
      ? 'Across mapped NYC ZIP areas with application records, there were ' + fmt(city.apps_per_1000) + ' cooling-assistance applications per 1,000 residents in 2025 (' + fmt(city.applications_2025) + ' applications). This uses the map’s population estimates and excludes five areas without application data.'
      : 'Citywide, ' + Number(city[c.field]).toFixed(1) + '% of New Yorkers identified as ' + (c.id === 'black' ? 'Black and non-Hispanic' : 'Hispanic, of any race') + ' in the 2020 Census.') + hviContext;
    status.textContent = help;
    table($('biv-table'), ['ZIP area', 'Neighborhoods', 'HVI (weighted)', c.title], d.features.map(f => [f.properties.label, f.properties.nta_names, fmt(f.properties.hvi_popwtd), fmt(f.properties[c.field])]));
  }
  l.comparisons.forEach(c => { const b = el('button', c.title); b.onclick = () => select(c); buttons.push([b, c.id]); $('tabs').append(b); });
  select(active);
}

for (const fn of [scrolly, zeroIn25, chart, bivariate]) {
  try { fn(); } catch (e) { console.error(e); document.querySelector('main, body').append(el('p', `Could not render ${fn.name}: ${e.message}`, 'note')); }
}
